val LocalWebStrings = staticCompositionLocalOf { englishWebStrings }

fun webStringsFor(language: WebLanguage): WebStrings = when (language) {
    WebLanguage.GERMAN -> germanWebStrings
    WebLanguage.SPANISH -> spanishWebStrings
    WebLanguage.FRENCH -> frenchWebStrings
    WebLanguage.PORTUGUESE -> portugueseWebStrings
    WebLanguage.RUSSIAN -> russianWebStrings
    else -> englishWebStrings
}

